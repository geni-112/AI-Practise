        "--user-name=$userName",
        "--region", $Region,
        "--candidate-project-id", $CandidateProjectId,
        "--duration-seconds", $CredentialDurationSeconds
    )
    $exchangeRaw = (& python @exchangeArguments | Out-String).Trim()
    $exchangeExitCode = $LASTEXITCODE
    Remove-Item Env:\HUAWEICLOUD_LOGIN_PASSWORD -ErrorAction SilentlyContinue
    $loginPassword = ""
    $exchange = $exchangeRaw | ConvertFrom-Json
    $exchangeRaw = ""
    if ($exchangeExitCode -ne 0 -or $exchange.status -ne "ready") {
        throw ([string]$exchange.error)
    }

    $env:HUAWEICLOUD_ACCESS_KEY = $exchange.access_key
    $env:HUAWEICLOUD_SECRET_KEY = $exchange.secret_key
    $env:HUAWEICLOUD_SECURITY_TOKEN = $exchange.security_token
    $env:HUAWEICLOUD_REGION = $Region
    $env:HUAWEICLOUD_PROJECT_ID = $exchange.project_id
