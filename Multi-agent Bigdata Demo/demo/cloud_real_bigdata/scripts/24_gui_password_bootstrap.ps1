}
catch {
    Remove-Item Env:\HUAWEICLOUD_LOGIN_PASSWORD -ErrorAction SilentlyContinue
    $loginPassword = ""
    $safeMessage = $_.Exception.Message
    if (-not $safeMessage) {
        $safeMessage = "The local password bootstrap failed before Huawei Cloud authentication."
    }
    [ordered]@{
        status = "failed"
        generated_at = (Get-Date).ToUniversalTime().ToString("o")
        login_password_persisted = $false
        iam_token_persisted = $false
        secret_values_printed = $false
        paid_resources_created = $false
