        private_key_path = $identity.private_key_path
        mrs_password_generated = $true
        secret_values_printed = $false
        paid_resources_created = $false
    } | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $bootstrapReportPath -Encoding UTF8

    $exchange = $null
    [System.Windows.Forms.MessageBox]::Show(
        "Temporary cloud session, MRS password, and ECS key pair are ready. No paid resources were created.",
        "Huawei Cloud connected",
        "OK",
        "Information"
    ) | Out-Null
