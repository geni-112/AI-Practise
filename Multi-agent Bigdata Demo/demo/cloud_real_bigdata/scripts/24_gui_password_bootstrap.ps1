    & python $identityHelper `
        --region $Region `
        --candidate-project-id $exchange.project_id `
        --key-dir $keyDir `
        --key-prefix $KeyPrefix `
        --report $identityReportPath
    if ($LASTEXITCODE -ne 0) {
        throw "Temporary credentials were issued, but ECS key-pair creation failed."
    }
    $identity = Get-Content -Raw -LiteralPath $identityReportPath -Encoding UTF8 | ConvertFrom-Json
    if ($identity.status -ne "ready") { throw "Cloud identity bootstrap did not reach ready status." }

    $mrsPassword = New-MrsPassword
    $pairs = Read-EnvPairs -Path $EnvFile
    $pairs.Remove("HUAWEICLOUD_LOGIN_PASSWORD")
    $pairs.Remove("OS_PASSWORD")
    $pairs.Remove("HW_USER_PASSWORD")
    $pairs["HUAWEICLOUD_ACCOUNT_NAME"] = $accountName
    $pairs["HUAWEICLOUD_ACCESS_KEY"] = $exchange.access_key
    $pairs["HUAWEICLOUD_SECRET_KEY"] = $exchange.secret_key
    $pairs["HUAWEICLOUD_SECURITY_TOKEN"] = $exchange.security_token
    $pairs["HUAWEICLOUD_CREDENTIAL_EXPIRES_AT"] = $exchange.expires_at
    $pairs["HUAWEICLOUD_REGION"] = $Region
    $pairs["HUAWEICLOUD_PROJECT_ID"] = $exchange.project_id
    $pairs["HW_ACCESS_KEY"] = $exchange.access_key
    $pairs["HW_SECRET_KEY"] = $exchange.secret_key
    $pairs["HW_SECURITY_TOKEN"] = $exchange.security_token
    $pairs["HW_REGION_NAME"] = $Region
    $pairs["HW_PROJECT_ID"] = $exchange.project_id
    $pairs["TF_VAR_region"] = $Region
    $pairs["TF_VAR_project_id"] = $exchange.project_id
    $pairs["TF_VAR_mrs_manager_admin_password"] = $mrsPassword
    $pairs["TF_VAR_node_key_pair_name"] = $identity.keypair_name
    Write-EnvPairs -Path $EnvFile -Pairs $pairs
    Protect-LocalSecretFile -Path $EnvFile
    Protect-LocalSecretFile -Path $identity.private_key_path

    [ordered]@{
        status = "ready"
        generated_at = (Get-Date).ToUniversalTime().ToString("o")
        region = $Region
        project_id = $exchange.project_id
        project_id_source = $exchange.project_id_source
        credential_type = "temporary_ak_sk_security_token"
        credential_expires_at = $exchange.expires_at
