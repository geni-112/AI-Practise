function Read-EnvPairs {
    param([string]$Path)
    $pairs = [ordered]@{}
    if (-not (Test-Path -LiteralPath $Path)) { return $pairs }
    foreach ($line in Get-Content -LiteralPath $Path -Encoding UTF8) {
        $trimmed = $line.Trim()
        if (-not $trimmed -or $trimmed.StartsWith("#")) { continue }
        $index = $trimmed.IndexOf("=")
        if ($index -le 0) { continue }
        $pairs[$trimmed.Substring(0, $index).Trim()] = $trimmed.Substring($index + 1)
    }
    return $pairs
}

function Write-EnvPairs {
    param([string]$Path, [System.Collections.IDictionary]$Pairs)
    $lines = @(
        "# Short-lived Huawei Cloud environment for SAT Agentic POC.",
        "# Generated by cloud_real_bigdata/scripts/24_gui_password_bootstrap.ps1.",
        "# The login password and IAM token are never stored.",
        "# This file is ignored by git. Never paste its values into chat or commit it.",
        ""
    )
    foreach ($name in $Pairs.Keys | Sort-Object) {
        $value = [string]$Pairs[$name]
        if ($value -match "[`r`n]") { throw "$name contains a newline." }
        $lines += "$name=$value"
    }
    $lines | Set-Content -LiteralPath $Path -Encoding UTF8
}

function New-MrsPassword {
    param([int]$Length = 20)
    $sets = @(
        "ABCDEFGHJKLMNPQRSTUVWXYZ",
        "abcdefghijkmnopqrstuvwxyz",
        "23456789",
        "!@#%*_-+="
    )
    $all = -join $sets
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $pick = {
            param([string]$Characters)
            $bytes = New-Object byte[] 4
            $rng.GetBytes($bytes)
            $Characters[[int]([BitConverter]::ToUInt32($bytes, 0) % [uint32]$Characters.Length)]
        }
        $characters = New-Object System.Collections.Generic.List[char]
        foreach ($set in $sets) { $characters.Add((& $pick $set)) }
        while ($characters.Count -lt $Length) { $characters.Add((& $pick $all)) }
        for ($i = $characters.Count - 1; $i -gt 0; $i--) {
            $bytes = New-Object byte[] 4
            $rng.GetBytes($bytes)
            $j = [int]([BitConverter]::ToUInt32($bytes, 0) % [uint32]($i + 1))
            $tmp = $characters[$i]
            $characters[$i] = $characters[$j]
            $characters[$j] = $tmp
        }
        return -join $characters
    }
    finally { $rng.Dispose() }
}

function Protect-LocalSecretFile {
    param([string]$Path)
    $resolvedPath = (Resolve-Path -LiteralPath $Path).Path
    $identity = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
    & icacls $resolvedPath /inheritance:r /grant:r "${identity}:(F)" "*S-1-5-18:(F)" | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw "Failed to restrict local secret file permissions: $resolvedPath"
    }
}

