function Read-EnvPairs {
    param([string]$Path)
    $pairs = [ordered]@{}
    if (-not (Test-Path -LiteralPath $Path)) {
        return $pairs
    }
    foreach ($line in Get-Content -LiteralPath $Path -Encoding UTF8) {
        $trimmed = $line.Trim()
        if (-not $trimmed -or $trimmed.StartsWith("#")) { continue }
        $index = $trimmed.IndexOf("=")
        if ($index -le 0) { continue }
        $name = $trimmed.Substring(0, $index).Trim()
        $value = $trimmed.Substring($index + 1)
        if ($name) { $pairs[$name] = $value }
    }
    return $pairs
}

function Write-EnvPairs {
    param(
        [string]$Path,
        [System.Collections.IDictionary]$Pairs
    )
    $lines = @(
        "# Local Huawei Cloud environment for SAT Agentic POC.",
        "# Generated by cloud_real_bigdata/scripts/23_gui_cloud_bootstrap.ps1.",
        "# This file is ignored by git. Never paste its values into chat or commit it.",
        ""
    )
    foreach ($name in $Pairs.Keys | Sort-Object) {
        $value = [string]$Pairs[$name]
        if ($value -match "[`r`n]") {
            throw "$name contains a newline."
        }
        $lines += "$name=$value"
    }
    $lines | Set-Content -LiteralPath $Path -Encoding UTF8
}

function New-MrsPassword {
    param([int]$Length = 20)
    $upper = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    $lower = "abcdefghijkmnopqrstuvwxyz"
    $digits = "23456789"
    $symbols = "!@#%*_-+="
    $all = $upper + $lower + $digits + $symbols
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        function Get-RandomIndex([int]$Maximum) {
            $bytes = New-Object byte[] 4
            $rng.GetBytes($bytes)
            return [int]([BitConverter]::ToUInt32($bytes, 0) % [uint32]$Maximum)
        }
        $characters = New-Object System.Collections.Generic.List[char]
        foreach ($set in @($upper, $lower, $digits, $symbols)) {
            $characters.Add($set[(Get-RandomIndex $set.Length)])
        }
        while ($characters.Count -lt $Length) {
            $characters.Add($all[(Get-RandomIndex $all.Length)])
        }
        for ($i = $characters.Count - 1; $i -gt 0; $i--) {
            $j = Get-RandomIndex ($i + 1)
            $tmp = $characters[$i]
            $characters[$i] = $characters[$j]
            $characters[$j] = $tmp
        }
        return -join $characters
    }
    finally {
        $rng.Dispose()
    }
}

function Protect-LocalSecretFile {
    param([string]$Path)
    $resolvedPath = (Resolve-Path -LiteralPath $Path).Path
    $identity = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
    & icacls $resolvedPath /inheritance:r /grant:r "${identity}:(F)" "*S-1-5-18:(F)" | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw "Failed to restrict local secret file permissions: $resolvedPath"
    }
}

