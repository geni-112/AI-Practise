$mrsPassword = New-MrsPassword
$env:HUAWEICLOUD_ACCOUNT_NAME = $accountName
$env:HUAWEICLOUD_ACCESS_KEY = $accessKey
$env:HUAWEICLOUD_SECRET_KEY = $secretKey
$env:HUAWEICLOUD_REGION = $Region

try {
    $helper = Join-Path $scriptDir "bootstrap_cloud_identity.py"
    $helperArgs = @(
        "--region", $Region,
        "--candidate-project-id", $CandidateProjectId,
        "--key-dir", $keyDir,
        "--key-prefix", $KeyPrefix,
        "--report", $identityReportPath
    )
    if ($CredentialsOnly) { $helperArgs += "--verify-only" }
    & python $helper @helperArgs
    if ($LASTEXITCODE -ne 0) {
        throw "Huawei Cloud rejected the credentials or project context. Check the local identity report."
    }

    $identityReport = Get-Content -Raw -LiteralPath $identityReportPath -Encoding UTF8 | ConvertFrom-Json
    if ($identityReport.status -ne "ready") {
        throw "Cloud identity bootstrap did not reach ready status."
    }

    $pairs = Read-EnvPairs -Path $EnvFile
    $pairs["HUAWEICLOUD_ACCOUNT_NAME"] = $accountName
    $pairs["HUAWEICLOUD_ACCESS_KEY"] = $accessKey
    $pairs["HUAWEICLOUD_SECRET_KEY"] = $secretKey
    $pairs["HUAWEICLOUD_REGION"] = $Region
    $pairs["HUAWEICLOUD_PROJECT_ID"] = $identityReport.project_id
    $pairs["HW_ACCESS_KEY"] = $accessKey
    $pairs["HW_SECRET_KEY"] = $secretKey
    $pairs["HW_REGION_NAME"] = $Region
    $pairs["HW_PROJECT_ID"] = $identityReport.project_id
    $pairs["TF_VAR_region"] = $Region
    $pairs["TF_VAR_project_id"] = $identityReport.project_id
    foreach ($temporaryName in @(
        "HUAWEICLOUD_SECURITY_TOKEN",
        "HUAWEICLOUD_CREDENTIAL_EXPIRES_AT",
        "HW_SECURITY_TOKEN"
    )) {
        if ($pairs.Contains($temporaryName)) { $pairs.Remove($temporaryName) }
    }
    if (-not $CredentialsOnly) {
        $pairs["TF_VAR_mrs_manager_admin_password"] = $mrsPassword
        $pairs["TF_VAR_node_key_pair_name"] = $identityReport.keypair_name
    }
    Write-EnvPairs -Path $EnvFile -Pairs $pairs
    Protect-LocalSecretFile -Path $EnvFile
    if (-not $CredentialsOnly) {
        Protect-LocalSecretFile -Path $identityReport.private_key_path
    }

    [ordered]@{
        status = "ready"
        generated_at = (Get-Date).ToUniversalTime().ToString("o")
        region = $Region
        project_id = $identityReport.project_id
        project_id_source = $identityReport.project_id_source
        cloud_keypair_created = [bool]$identityReport.cloud_keypair_created
        keypair_name = if ($CredentialsOnly) { $pairs["TF_VAR_node_key_pair_name"] } else { $identityReport.keypair_name }
        private_key_path = if ($CredentialsOnly) { "" } else { $identityReport.private_key_path }
        mrs_password_generated = (-not $CredentialsOnly)
        credentials_only = [bool]$CredentialsOnly
        env_file = $EnvFile
        secret_values_printed = $false
        paid_resources_created = $false
        next_action = ".\cloud_real_bigdata\scripts\15_pre_apply_readiness.ps1 -EnableWebEcs -RunReadonlyCloudProbe -RunTerraformPreflight"
    } | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $bootstrapReportPath -Encoding UTF8

    $successMessage = if ($CredentialsOnly) {
        "Permanent credentials verified. Existing MRS and ECS settings were preserved. No cloud resources were created."
    }
    else {
        "Credentials verified. Project context, MRS password, and ECS key pair are ready. No paid resources were created."
    }
    [System.Windows.Forms.MessageBox]::Show(
        $successMessage,
        "Huawei Cloud connected",
        "OK",
        "Information"
    ) | Out-Null
    exit 0
}
catch {
    $safeMessage = $_.Exception.Message.Replace($accessKey, "<redacted>").Replace($secretKey, "<redacted>")
    [ordered]@{
        status = "failed"
        generated_at = (Get-Date).ToUniversalTime().ToString("o")
        secret_values_printed = $false
        paid_resources_created = $false
        error = $safeMessage
        identity_report = $identityReportPath
    } | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath $bootstrapReportPath -Encoding UTF8
    [System.Windows.Forms.MessageBox]::Show(
        "$safeMessage`n`nNo paid resources were created.",
        "Huawei Cloud connection failed",
        "OK",
        "Error"
    ) | Out-Null
    exit 1
}
