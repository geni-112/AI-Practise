  const sourceText = new WeakMap();
  const renderedText = new WeakMap();
  const sourceAttributes = new WeakMap();
  const renderedAttributes = new WeakMap();

  function translate(value) {
    if (locale !== "en" || typeof value !== "string") return value;
    const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const leading = match?.[1] || "";
    const body = match?.[2] || value;
    const trailing = match?.[3] || "";
    if (!body) return value;
    const exact = english.get(body);
    if (exact) return `${leading}${exact}${trailing}`;
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(body)) return `${leading}${body.replace(pattern, replacement)}${trailing}`;
    }
    return value;
  }

  function ignored(element) {
    return !element || Boolean(element.closest(
      "script, style, textarea, pre, code, [data-i18n-ignore], .chat-turn-user, #userPromptMessage",
    ));
  }

  function ignoredAttribute(element) {
    return !element || Boolean(element.closest("script, style, [data-i18n-ignore]"));
  }

  function applyTextNode(textNode) {
    if (ignored(textNode.parentElement)) return;
    const current = textNode.nodeValue || "";
    const lastRendered = renderedText.get(textNode);
    if (!sourceText.has(textNode) || current !== lastRendered) sourceText.set(textNode, current);
    const source = sourceText.get(textNode) || "";
    const next = locale === "en" ? translate(source) : source;
    renderedText.set(textNode, next);
    if (current !== next) textNode.nodeValue = next;
  }

  function applyAttribute(element, name) {
    if (ignoredAttribute(element) || !element.hasAttribute(name)) return;
    const current = element.getAttribute(name) || "";
    let sources = sourceAttributes.get(element);
    let rendered = renderedAttributes.get(element);
    if (!sources) {
      sources = {};
      sourceAttributes.set(element, sources);
    }
    if (!rendered) {
      rendered = {};
      renderedAttributes.set(element, rendered);
    }
    if (!(name in sources) || current !== rendered[name]) sources[name] = current;
    const next = locale === "en" ? translate(sources[name]) : sources[name];
    rendered[name] = next;
    if (current !== next) element.setAttribute(name, next);
  }

  function applyElement(root = document.body) {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    if (root.nodeType === Node.TEXT_NODE) applyTextNode(root);
    let textNode = walker.nextNode();
    while (textNode) {
      applyTextNode(textNode);
      textNode = walker.nextNode();
    }
    const elements = root.nodeType === Node.ELEMENT_NODE
      ? [root, ...root.querySelectorAll("[placeholder], [title], [aria-label]")]
      : [];
    elements.forEach((element) => {
      ["placeholder", "title", "aria-label"].forEach((name) => applyAttribute(element, name));
    });
  }

  function updateControls() {
    document.documentElement.lang = locale === "en" ? "en" : "zh-CN";
    document.querySelectorAll("[data-locale]").forEach((button) => {
      const active = button.dataset.locale === locale;
      button.classList.toggle("is-active", active);
      button.setAttribute("aria-pressed", String(active));
    });
  }

  function setLocale(nextLocale) {
    if (!SUPPORTED.has(nextLocale) || nextLocale === locale) return;
    locale = nextLocale;
    localStorage.setItem(STORAGE_KEY, locale);
    updateControls();
    applyElement(document.body);
    window.dispatchEvent(new CustomEvent("app:localechange", { detail: { locale } }));
  }

  function setText(element, source) {
    element.textContent = source ?? "";
    const textNode = element.firstChild;
    if (textNode?.nodeType === Node.TEXT_NODE) {
      sourceText.set(textNode, String(source ?? ""));
      applyTextNode(textNode);
    }
  }

  function init() {
    updateControls();
    document.querySelectorAll("[data-locale]").forEach((button) => {
      button.addEventListener("click", () => setLocale(button.dataset.locale));
    });
    applyElement(document.body);
    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === "characterData") {
          applyTextNode(mutation.target);
          return;
        }
        if (mutation.type === "attributes") {
          applyAttribute(mutation.target, mutation.attributeName);
          return;
        }
        mutation.addedNodes.forEach((added) => {
          if (added.nodeType === Node.TEXT_NODE) applyTextNode(added);
          if (added.nodeType === Node.ELEMENT_NODE) applyElement(added);
        });
      });
    });
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["placeholder", "title", "aria-label"],
    });
  }

  window.i18n = {
    get locale() { return locale; },
    t: translate,
    setLocale,
    setText,
    refresh: () => applyElement(document.body),
  };

  init();
