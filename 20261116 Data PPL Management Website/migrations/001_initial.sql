CREATE TABLE IF NOT EXISTS records (
  id VARCHAR(190) PRIMARY KEY,
  kind VARCHAR(20) NOT NULL,
  payload LONGTEXT NOT NULL CHECK (JSON_VALID(payload)),
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0), INDEX records_kind_idx(kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS members (
  email VARCHAR(190) PRIMARY KEY,
  user_id VARCHAR(190) UNIQUE,
  role_id VARCHAR(190) NOT NULL, FOREIGN KEY (role_id) REFERENCES records(id),
  enabled INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  version INTEGER NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit (id VARCHAR(190) PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL, entity TEXT NOT NULL, at VARCHAR(30) NOT NULL, INDEX audit_date_idx(at)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS accounts (
  email VARCHAR(190) PRIMARY KEY, FOREIGN KEY (email) REFERENCES members(email),
  password_hash VARCHAR(255) NOT NULL,
  changed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
  token_hash VARCHAR(190) PRIMARY KEY,
  email VARCHAR(190) NOT NULL, FOREIGN KEY (email) REFERENCES accounts(email),
  expires_at DATETIME NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX sessions_email_idx(email), INDEX sessions_expiry_idx(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


CREATE TABLE IF NOT EXISTS invitations (
  token_hash VARCHAR(190) PRIMARY KEY,
  email VARCHAR(190) NOT NULL, FOREIGN KEY (email) REFERENCES members(email),
  expires_at DATETIME NOT NULL,
  created_by TEXT NOT NULL,
  used_at DATETIME
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_limits (
  `key` VARCHAR(190) PRIMARY KEY,
  attempts INTEGER NOT NULL DEFAULT 1,
  reset_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
